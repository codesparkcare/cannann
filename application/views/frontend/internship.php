<script>
    // Initialize Swiper - wait for library to load
    function initTrainingSwiper() {
        if (typeof Swiper === 'undefined') {
            setTimeout(initTrainingSwiper, 100);
            return;
        }
        if (document.querySelector('.training-swiper')) {
            new Swiper('.training-swiper', {
                slidesPerView: 1,
                spaceBetween: 20,
                loop: true,
                grabCursor: true,
                autoplay: {
                    delay: 4500,
                    disableOnInteraction: false,
                    pauseOnMouseEnter: true,
                },
                pagination: {
                    el: '.training-swiper-pagination',
                    clickable: true,
                },
                navigation: {
                    nextEl: '.training-swiper-next',
                    prevEl: '.training-swiper-prev',
                },
                breakpoints: {
                    576: { slidesPerView: 1, spaceBetween: 16 },
                    768: { slidesPerView: 2, spaceBetween: 20 },
                    1024: { slidesPerView: 3, spaceBetween: 24 }
                }
            });
        }
    }
    // Try to init after DOM is ready
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initTrainingSwiper);
    } else {
        initTrainingSwiper();
    }

    function openApplyModalWithDept(deptName) {
        const modalDept = document.getElementById('modal_intern_dept');
        if (modalDept) {
            modalDept.value = deptName;
        }
        const pageDept = document.getElementById('page_intern_dept');
        if (pageDept) {
            pageDept.value = deptName;
        }
        const modal = new bootstrap.Modal(document.getElementById('applyInternshipModal'));
        modal.show();
    }

    // AJAX Form Handling for On-page Form
    document.getElementById('internshipPageForm')?.addEventListener('submit', function(e) {
        e.preventDefault();
        const form = this;
        const btn = document.getElementById('btnSubmitInternshipPage');
        const alertBox = document.getElementById('pageApplicationAlert');

        btn.disabled = true;
        btn.innerHTML = '<i class="fa-solid fa-spinner fa-spin me-2"></i> Submitting Application...';

        const formData = new FormData(form);

        fetch('<?php echo base_url("apply-internship"); ?>', {
            method: 'POST',
            body: formData,
            headers: { 'X-Requested-With': 'XMLHttpRequest' }
        })
        .then(res => res.json())
        .then(data => {
            btn.disabled = false;
            btn.innerHTML = '<i class="fa-solid fa-paper-plane me-2"></i> Submit Internship Application';
            if (data.status === 'success') {
                form.reset();
                if (alertBox) alertBox.innerHTML = '';
                if (typeof showThankYouPopup === 'function') {
                    showThankYouPopup(
                        'Internship Application Submitted!',
                        'Thank you for applying to the Canaan Hotel Internship Program. Your application has been successfully received. Our HR & Training team will review your profile and contact you soon.'
                    );
                } else {
                    alertBox.innerHTML = '<div class="alert alert-success d-flex align-items-center gap-2 mb-3"><i class="fa-solid fa-circle-check fs-5"></i><div>' + data.message + '</div></div>';
                }
            } else {
                alertBox.innerHTML = '<div class="alert alert-danger d-flex align-items-center gap-2 mb-3"><i class="fa-solid fa-triangle-exclamation fs-5"></i><div>' + data.message + '</div></div>';
            }
        })
        .catch(err => {
            btn.disabled = false;
            btn.innerHTML = '<i class="fa-solid fa-paper-plane me-2"></i> Submit Internship Application';
            form.submit();
        });
    });

    // AJAX Form Handling for Modal Form
    document.getElementById('internshipModalForm')?.addEventListener('submit', function(e) {
        e.preventDefault();
        const form = this;
        const btn = document.getElementById('btnSubmitInternshipModal');
        const alertBox = document.getElementById('modalApplicationAlert');

        btn.disabled = true;
        btn.innerHTML = '<i class="fa-solid fa-spinner fa-spin me-2"></i> Submitting Application...';

        const formData = new FormData(form);

        fetch('<?php echo base_url("apply-internship"); ?>', {
            method: 'POST',
            body: formData,
            headers: { 'X-Requested-With': 'XMLHttpRequest' }
        })
        .then(res => res.json())
        .then(data => {
            btn.disabled = false;
            btn.innerHTML = '<i class="fa-solid fa-paper-plane me-2"></i> Submit Application';
            if (data.status === 'success') {
                form.reset();
                if (alertBox) alertBox.innerHTML = '';
                const modalEl = document.getElementById('applyInternshipModal');
                if (modalEl) {
                    const modal = bootstrap.Modal.getInstance(modalEl);
                    if (modal) modal.hide();
                }
                if (typeof showThankYouPopup === 'function') {
                    showThankYouPopup(
                        'Internship Application Submitted!',
                        'Thank you for applying to the Canaan Hotel Internship Program. Your application has been successfully received. Our HR & Training team will review your profile and contact you soon.'
                    );
                } else {
                    alertBox.innerHTML = '<div class="alert alert-success d-flex align-items-center gap-2 mb-3"><i class="fa-solid fa-circle-check fs-5"></i><div>' + data.message + '</div></div>';
                }
            } else {
                alertBox.innerHTML = '<div class="alert alert-danger d-flex align-items-center gap-2 mb-3"><i class="fa-solid fa-triangle-exclamation fs-5"></i><div>' + data.message + '</div></div>';
            }
        })
        .catch(err => {
            btn.disabled = false;
            btn.innerHTML = '<i class="fa-solid fa-paper-plane me-2"></i> Submit Application';
            form.submit();
        });
    });
</script>
